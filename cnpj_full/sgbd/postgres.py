# -*- encoding: utf-8 -*-
'''
Carga no PostgreSQL, com COPY (o jeito mais rapido de inserir em massa).

Tabelas, colunas e tipos seguem o modelo do cnpjrfb
(docs/modelo_banco/postgresql/modelo_postgres.sql), no schema dados_rfb:
codigos de dominio INTEGER, datas DATE, capital_social NUMERIC(18,2) e
textos TEXT (sem limite de tamanho, para que um valor maior que o previsto
nao interrompa a carga). Chaves primarias e indices sao criados no fim.

Cada arquivo da RF e gravado em uma unica transacao, junto com o seu
registro na controle_carga. Se a carga for interrompida, o PostgreSQL
desfaz o arquivo que estava sendo gravado, e --continuar sempre pode
retomar (nao ha diferenca entre modo rapido e seguro).

Requer: pip install "psycopg[binary]"
'''
import io
import sys
import datetime

import pandas as pd

from cnpj_full import cnpj

SCHEMA_PADRAO = 'dados_rfb'
PORTA_PADRAO = 5432

TIPOS = {
    'INTEGER': 'INTEGER',
    'REAL': 'NUMERIC(18,2)',
    'TEXT': 'TEXT',
}
# Maior valor que cabe em NUMERIC(18,2)
LIMITE_NUMERIC = 10 ** 16

# Chaves primarias do modelo do cnpjrfb (criadas depois da carga)
CHAVES_PRIMARIAS = {
    cnpj.EMPRESA: 'cnpj_basico',
    cnpj.ESTABELECIMENTO: 'cnpj_basico, cnpj_ordem, cnpj_dv',
    cnpj.SIMPLES: 'cnpj_basico',
    cnpj.SOCIOS: 'id',
    cnpj.CNAE: 'codigo',
    cnpj.MOTIVO: 'codigo',
    cnpj.MUNICIPIO: 'codigo',
    cnpj.NATUREZA: 'codigo',
    cnpj.PAIS: 'codigo',
    cnpj.QUALIFICACAO: 'codigo',
}

# Indices alem das chaves primarias (os mesmos do SQLite)
INDICES = [i for i in cnpj.INDICES if not i[0].endswith('_codigo')]


def importa_psycopg():
    try:
        import psycopg
    except ImportError:
        print(u'ERRO: para gravar no PostgreSQL instale o driver: pip install "psycopg[binary]"',
              file=sys.stderr)
        sys.exit(-1)
    return psycopg


def _agora():
    return datetime.datetime.now().replace(microsecond=0)


class Destino(object):

    def __init__(self, config):
        psycopg = importa_psycopg()
        self.psycopg = psycopg
        self.schema = config.get('schema') or SCHEMA_PADRAO
        self.parametros = {
            'host': config.get('host') or 'localhost',
            'port': int(config.get('porta') or PORTA_PADRAO),
            'dbname': config.get('nome') or 'dados_rfb',
            'user': config.get('usuario') or 'postgres',
            'password': config.get('senha') or None,
            'application_name': 'cnpj-full',
        }
        self.con = self._conecta()
        with self.con.cursor() as cur:
            # A durabilidade de cada arquivo vem do COMMIT; sem esperar o
            # fsync de cada transacao a carga fica mais rapida e continua
            # consistente (no pior caso perde-se o ultimo arquivo gravado,
            # que o --continuar carrega de novo).
            cur.execute('SET synchronous_commit TO off')
            cur.execute('CREATE SCHEMA IF NOT EXISTS {}'.format(self.schema))
        self.con.commit()
        print(u'PostgreSQL: {user}@{host}:{port}/{dbname}, schema {schema}'.format(
            schema=self.schema, **self.parametros))

    def _conecta(self):
        psycopg = self.psycopg
        try:
            return psycopg.connect(**self.parametros)
        except psycopg.OperationalError as erro:
            if 'does not exist' not in str(erro) and 'nao existe' not in str(erro) \
                    and u'não existe' not in str(erro):
                raise
        # Banco ainda nao existe: cria, conectando no banco padrao "postgres"
        nome = self.parametros['dbname']
        print(u'Criando o banco {}...'.format(nome))
        admin = dict(self.parametros, dbname='postgres')
        with psycopg.connect(autocommit=True, **admin) as con:
            con.execute("CREATE DATABASE {} WITH ENCODING 'UTF8' TEMPLATE template0".format(
                psycopg.sql.Identifier(nome).as_string(con)))
        return psycopg.connect(**self.parametros)

    def t(self, tabela):
        return '{}.{}'.format(self.schema, tabela)

    # -- estrutura ----------------------------------------------------------

    def _ddl_tabela(self, tabela):
        colunas = []
        if tabela == cnpj.SOCIOS:
            colunas.append('id BIGINT GENERATED BY DEFAULT AS IDENTITY')
        datas = cnpj.COLUNAS_DATA.get(tabela, [])
        for nome, tipo in cnpj.COLUNAS[tabela]:
            colunas.append('{} {}'.format(nome, 'DATE' if nome in datas else TIPOS[tipo]))
        return 'CREATE TABLE {} ({})'.format(self.t(tabela), ', '.join(colunas))

    def _ddl_controle(self):
        return '''CREATE TABLE IF NOT EXISTS {} (
                    tabela TEXT,
                    arquivo TEXT,
                    membro TEXT,
                    modo TEXT,
                    linhas_arquivo BIGINT,
                    registros_lidos BIGINT,
                    registros_descartados BIGINT,
                    registros_gravados BIGINT,
                    status TEXT,
                    observacao TEXT,
                    inicio TIMESTAMP,
                    fim TIMESTAMP)'''.format(self.t(cnpj.CONTROLE))

    def cria_tabelas(self, tabelas):
        with self.con.cursor() as cur:
            for tabela in tabelas:
                cur.execute('DROP TABLE IF EXISTS {} CASCADE'.format(self.t(tabela)))
                cur.execute(self._ddl_tabela(tabela))
            cur.execute('DROP TABLE IF EXISTS {}'.format(self.t(cnpj.CONTROLE)))
            cur.execute(self._ddl_controle())
        self.con.commit()

    def _tabelas_existentes(self, cur):
        cur.execute('SELECT table_name FROM information_schema.tables WHERE table_schema = %s',
                    (self.schema,))
        return set(r[0] for r in cur.fetchall())

    def prepara_continuacao(self, tabelas):
        with self.con.cursor() as cur:
            existentes = self._tabelas_existentes(cur)
            if cnpj.CONTROLE not in existentes:
                print(u'ERRO: Nao ha carga anterior para continuar neste banco. '
                      u'Rode a carga sem --continuar.')
                sys.exit(-1)
            for tabela in tabelas:
                if tabela not in existentes:
                    cur.execute(self._ddl_tabela(tabela))
            concluidos = set()
            totais = {t: 0 for t in tabelas}
            cur.execute('SELECT tabela, arquivo, membro, registros_gravados FROM {}'.format(
                self.t(cnpj.CONTROLE)))
            for tabela, arquivo, membro, registros in cur.fetchall():
                concluidos.add((arquivo, membro or ''))
                if tabela in totais:
                    totais[tabela] += registros or 0
        self.con.commit()
        return concluidos, totais

    # -- carga --------------------------------------------------------------

    @staticmethod
    def prepara_bloco(tabela, df):
        '''Converte o bloco para o formato do COPY: codigos inteiros, datas
        AAAA-MM-DD e sem caracteres NUL (que o PostgreSQL nao aceita em texto).
        Valores invalidos (ex: data 20241399) viram NULL.'''
        datas = cnpj.COLUNAS_DATA.get(tabela, [])
        for nome, tipo in cnpj.COLUNAS[tabela]:
            if nome in datas:
                df[nome] = pd.to_datetime(df[nome], format='%Y%m%d', errors='coerce').dt.strftime('%Y-%m-%d')
            elif tipo == 'INTEGER':
                df[nome] = pd.to_numeric(df[nome], errors='coerce').astype('Int64')
            elif tipo == 'REAL':
                valores = pd.to_numeric(df[nome], errors='coerce')
                df[nome] = valores.mask(valores.abs() >= LIMITE_NUMERIC)
            else:
                df[nome] = df[nome].str.replace('\x00', '', regex=False)
        return df

    def grava_arquivo(self, tabela, caminho, membro, totais, modo=cnpj.MODO_RAPIDO):
        arquivo, nome_membro = cnpj.id_arquivo(caminho, membro)
        inicio = _agora()
        nomes = [c[0] for c in cnpj.COLUNAS[tabela]]
        sql_copy = 'COPY {} ({}) FROM STDIN WITH (FORMAT csv)'.format(self.t(tabela), ', '.join(nomes))

        est = cnpj.novas_estatisticas()
        try:
            with self.con.cursor() as cur:
                with cur.copy(sql_copy) as copy:
                    for i_bloco, df in enumerate(cnpj.le_arquivo(tabela, caminho, membro, est)):
                        df = self.prepara_bloco(tabela, df)
                        buffer = io.StringIO()
                        df.to_csv(buffer, header=False, index=False, na_rep='')
                        copy.write(buffer.getvalue())
                        print('Bloco {}: {} registros de {} ate agora.'.format(
                            i_bloco + 1, totais[tabela] + est['registros_lidos'], tabela), end='\r')
                est['registros_gravados'] = max(cur.rowcount, 0)
                status, observacao = cnpj.avalia_estatisticas(est)
                cur.execute('INSERT INTO {} (tabela, arquivo, membro, modo, linhas_arquivo, '
                            'registros_lidos, registros_descartados, registros_gravados, '
                            'status, observacao, inicio, fim) '
                            'VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)'.format(
                                self.t(cnpj.CONTROLE)),
                            (tabela, arquivo, nome_membro, 'postgres', est['linhas_arquivo'],
                             est['registros_lidos'], est['registros_descartados'],
                             est['registros_gravados'], status, observacao, inicio, _agora()))
            self.con.commit()
        except BaseException:
            # O PostgreSQL desfaz tudo o que foi gravado deste arquivo
            self.con.rollback()
            raise

        totais[tabela] += est['registros_gravados']

    def verificacao(self):
        colunas = ['tabela', 'arquivo', 'membro', 'linhas_arquivo', 'registros_lidos',
                   'registros_descartados', 'registros_gravados', 'status', 'observacao']
        with self.con.cursor() as cur:
            cur.execute('SELECT {} FROM {} ORDER BY inicio, arquivo, membro'.format(
                ', '.join(colunas), self.t(cnpj.CONTROLE)))
            linhas = [dict(zip(colunas, linha)) for linha in cur.fetchall()]
        self.con.commit()
        return linhas

    # -- indices ------------------------------------------------------------

    def cria_indices(self):
        print(u'''
Criando chaves primarias e indices...
Essa operacao pode levar varios minutos.
    ''')
        self.con.autocommit = True
        try:
            with self.con.cursor() as cur:
                existentes = self._tabelas_existentes(cur)
                for tabela, colunas in CHAVES_PRIMARIAS.items():
                    if tabela not in existentes:
                        continue
                    nome = 'pk_' + tabela
                    cur.execute('SELECT 1 FROM pg_constraint c JOIN pg_namespace n ON n.oid = c.connamespace '
                                'WHERE n.nspname = %s AND c.conname = %s', (self.schema, nome))
                    if cur.fetchone():
                        continue
                    try:
                        cur.execute('ALTER TABLE {} ADD CONSTRAINT {} PRIMARY KEY ({})'.format(
                            self.t(tabela), nome, colunas))
                        print(u'Chave primaria {} criada.'.format(nome))
                    except self.psycopg.Error as erro:
                        # Ex: registros duplicados no arquivo da RF. Cria um indice
                        # comum no lugar, para as consultas continuarem rapidas.
                        print(u'AVISO: chave primaria {} nao criada ({}). Criando indice comum.'.format(
                            nome, str(erro).strip().splitlines()[0]), file=sys.stderr)
                        cur.execute('CREATE INDEX IF NOT EXISTS {} ON {} ({})'.format(
                            cnpj.PREFIXO_INDICE + tabela + '_pk', self.t(tabela), colunas))

                for nome, tabela, colunas in INDICES:
                    if tabela not in existentes or colunas == CHAVES_PRIMARIAS.get(tabela):
                        continue
                    nome_indice = cnpj.PREFIXO_INDICE + nome
                    cur.execute('CREATE INDEX IF NOT EXISTS {} ON {} ({})'.format(
                        nome_indice, self.t(tabela), colunas))
                    print(u'Index {} criado.'.format(nome_indice))

                for tabela in sorted(existentes & set(CHAVES_PRIMARIAS)):
                    cur.execute('ANALYZE {}'.format(self.t(tabela)))
            print(u'Indices criados com sucesso.')
        finally:
            self.con.autocommit = False

    def fecha(self):
        self.con.close()
